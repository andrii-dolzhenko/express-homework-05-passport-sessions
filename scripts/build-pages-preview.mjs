let exitCode = 0
try {
  await waitForServer()
  await rm(OUTPUT, { recursive: true, force: true })
  await mkdir(OUTPUT, { recursive: true })
  await cp(resolve('src/public'), join(OUTPUT, 'assets'), { recursive: true })
  await cp(resolve('src/public/favicon.ico'), join(OUTPUT, 'favicon.ico'))

  const cssFile = join(OUTPUT, 'assets/css/demo.css')
  await writeFile(cssFile, (await readFile(cssFile, 'utf8')) + previewCss, 'utf8')

  const client = await readFile(resolve('scripts/pages-preview.js'), 'utf8')
  await writeFile(join(OUTPUT, 'assets/js/pages-preview.js'), client, 'utf8')

  const dashboard = await (await get('/demo')).text()
  await savePage('', dashboard, true)
  await savePage('demo', dashboard, true)
  await savePage('demo/icon', await (await get('/demo/icon')).text())

  const users = await (await get('/users', 'application/json')).json()
  const articles = await (await get('/articles', 'application/json')).json()
  if (!Array.isArray(users) || !Array.isArray(articles)) {
    throw new Error('Expected JSON collections from Express')
  }

  await savePage('users', await (await get('/users')).text())
  await savePage('articles', await (await get('/articles')).text())

  for (const user of users) {
    const id = safeSegment(user.id)
    await savePage('users/' + id, await (await get('/users/' + id)).text())
  }
  for (const article of articles) {
    const id = safeSegment(article.id)
    await savePage('articles/' + id, await (await get('/articles/' + id)).text())
  }

  console.log('Exported static dashboard, icon, and ' +
    (2 + users.length + articles.length) + ' PUG/EJS pages into .pages-dist')
  console.log('All auth/session actions are disabled; theme colors are a client-only preview.')
} catch (error) {
  exitCode = 1
  console.error('Static Pages export failed:', error)
} finally {
  await new Promise((done) => server.close(() => done()))
}
process.exitCode = exitCode
