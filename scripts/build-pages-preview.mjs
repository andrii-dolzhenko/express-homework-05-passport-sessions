// Export server-rendered pages as a read-only GitHub Pages preview.
// Real authentication, cookies, CRUD mutations and sessions require local Express.
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { JSDOM } from 'jsdom'
import { server } from '../src/server.mjs'

const OUTPUT = resolve('.pages-dist')
const BASE = (process.env.PAGES_BASE_PATH || '/express-homework-05-passport-sessions').replace(/\/$/, '')
const ORIGIN = 'http://127.0.0.1:3000'

if (!/^\/[a-zA-Z0-9/_-]+$/.test(BASE)) {
  throw new Error('Invalid PAGES_BASE_PATH')
}

function waitForServer() {
  if (server.listening) return Promise.resolve()
  return new Promise((done, fail) => {
    server.once('listening', done)
    server.once('error', fail)
  })
}

async function get(route, accept = 'text/html') {
  const response = await fetch(ORIGIN + route, { headers: { Accept: accept } })
  if (!response.ok) throw new Error(route + ': HTTP ' + response.status)
  return response
}

function safeSegment(value) {
  if (typeof value !== 'string' || !/^[a-zA-Z0-9_-]+$/.test(value)) {
    throw new Error('Unsafe static path segment: ' + JSON.stringify(value))
  }
  return value
}

function staticUrl(url) {
  const match = /^(\/[^?#]*)([?#].*)?$/.exec(url)
  if (!match) return url
  const route = match[1]
  const suffix = match[2] || ''
  if (route === '/') return BASE + '/' + suffix
  if (route.startsWith('/assets/') || route === '/favicon.ico') {
    return BASE + route + suffix
  }
  if (/^\/(?:demo|users|articles)(?:\/|$)/.test(route)) {
    return BASE + route.replace(/\/$/, '') + '/' + suffix
  }
  throw new Error('Unsupported root-relative static preview URL: ' + url)
}

function makeThemeControlsClientOnly(document) {
  for (const form of [...document.querySelectorAll('form.theme-form')]) {
    const wrapper = document.createElement('div')
    wrapper.className = form.className
    wrapper.setAttribute('role', 'group')
    wrapper.setAttribute('aria-label', 'Preview-only color scheme')
    for (const button of form.querySelectorAll('button.theme-btn')) {
      button.type = 'button'
      button.dataset.previewTheme = button.value
      button.removeAttribute('name')
      wrapper.append(button)
    }
    form.replaceWith(wrapper)
  }
}

function disableServerControls(document) {
  const selectors = [
    '#auth-form input', '#auth-form button', '.demo-tabs button',
    '#check-access', '#demo-logout', '#session-check',
  ]
  for (const element of document.querySelectorAll(selectors.join(', '))) {
    element.disabled = true
    element.title = 'Requires the locally running Express server'
  }

  const update = (selector, message) => {
    const node = document.querySelector(selector)
    if (node) node.textContent = message
  }
  update('.demo-intro .eyebrow', 'STATIC PREVIEW · GITHUB PAGES')
  update('.demo-intro .lead',
    'Explore the UI generated by Express. Authentication, server-side cookies and session requests require the locally running application.')
  update('#auth-state-label', 'Preview mode — not signed in')
  update('#auth-state-detail',
    'No authentication request is sent in this preview. Start Express locally to register, sign in, or verify your Passport session.')
  update('#auth-response', 'Static preview: no live API response.\nRun npm start locally to test GET /auth/me.')
  update('#access-feedback', 'Authentication and protected routes require local Express.')
  update('#auth-feedback', 'Registration and sign-in are disabled on GitHub Pages.')
  update('#session-feedback', 'The visit counter requires an Express server.')
  update('.status-topline span:last-child', 'STATIC PREVIEW')
  update('.demo-disclaimer',
    'Static visual preview. Local Express is required for registration, Passport session verification, cookies, sessions and REST mutations.')

  const dot = document.querySelector('.status-live-dot')
  if (dot) dot.remove()

  const themeDescription = document.querySelector('#theme-title')?.closest('section')?.querySelector('.panel-description')
  if (themeDescription) {
    themeDescription.textContent =
      'This preview changes the color scheme only in your browser. Saving a theme in an Express cookie requires the local server.'
  }

  const authPanel = document.querySelector('#auth-title')?.closest('section')
  if (authPanel) {
    const note = document.createElement('p')
    note.className = 'preview-disabled-note'
    note.textContent = 'Live registration and login are available after running npm start.'
    authPanel.append(note)
  }
}

function previewBanner(document) {
  const main = document.querySelector('main')
  if (!main) throw new Error('Expected a semantic main element')
  const banner = document.createElement('aside')
  banner.className = 'preview-banner'
  banner.setAttribute('aria-label', 'Static preview limitations')
  const strong = document.createElement('strong')
  strong.textContent = 'Static preview'
  const span = document.createElement('span')
  span.textContent =
    'These pages were rendered by Express during the build. Theme colors can be previewed in this browser. Registration, Passport authentication, session cookies and API changes require npm start locally.'
  banner.append(strong, span)
  main.prepend(banner)
}

function prepare(html, isDashboard = false) {
  const dom = new JSDOM(html)
  const document = dom.window.document

  makeThemeControlsClientOnly(document)
  if (isDashboard) disableServerControls(document)

  // Never load the live demo client: its fetch calls would target GitHub Pages.
  for (const script of document.querySelectorAll('script[src]')) {
    if (script.getAttribute('src') === '/assets/js/demo.js') script.remove()
  }
  previewBanner(document)

  for (const element of document.querySelectorAll('[href], [src]')) {
    for (const attribute of ['href', 'src']) {
      const url = element.getAttribute(attribute)
      if (url?.startsWith('/') && !url.startsWith('//')) {
        element.setAttribute(attribute, staticUrl(url))
      }
    }
  }

  const script = document.createElement('script')
  script.src = BASE + '/assets/js/pages-preview.js'
  script.defer = true
  document.head.append(script)

  if (document.querySelector('script[src$="/assets/js/demo.js"]')) {
    throw new Error('Live backend JavaScript must not be loaded in static preview')
  }
  return '<!DOCTYPE html>\n' + document.documentElement.outerHTML + '\n'
}

async function savePage(relative, html, isDashboard = false) {
  const file = join(OUTPUT, relative, 'index.html')
  await mkdir(dirname(file), { recursive: true })
  await writeFile(file, prepare(html, isDashboard), 'utf8')
}

